func init() {
	// Merge OmniRouteRegistry into main Registry if not already present
	existing := make(map[string]bool)
	for _, e := range Registry {
		existing[e.ID] = true
	}
	for _, e := range OmniRouteRegistry {
		if !existing[e.ID] {
			Registry = append(Registry, e)
			existing[e.ID] = true
		}
	}
}
